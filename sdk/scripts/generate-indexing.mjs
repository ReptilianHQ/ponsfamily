#!/usr/bin/env node
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { stringify } from 'yaml';
import { toEventSignature } from 'viem';
import { getPonsIndexingManifest, ponsIndexingAbis } from '../dist/indexing.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const banner = '// Generated by scripts/generate-indexing.mjs. Edit src/indexing.ts and regenerate.\n';
const json = value => JSON.stringify(value, (_, item) => typeof item === 'bigint' ? item.toString() : item, 2) + '\n';
const q = JSON.stringify;
const ident = value => assert.match(value, /^[A-Za-z][A-Za-z0-9_]*$/, `Invalid identifier: ${value}`);

export function validateCatalog(manifest) {
  const eventFor = (contract, name) => {
    const matches = manifest.catalog.filter(event => event.contract === contract && event.name === name);
    assert.equal(matches.length, 1, `Unknown or ambiguous event ${contract}.${name}`);
    return matches[0];
  };
  const parameter = (event, name) => {
    const result = event.parameters.find(p => p.name === name);
    assert.ok(result, `Unknown parameter ${event.contract}.${event.name}.${name}`);
    return result;
  };
  const keys = new Set();
  for (const event of manifest.catalog) {
    ident(event.contract); ident(event.name);
    const key = `${event.contract}.${event.signature}`;
    assert.ok(!keys.has(key), `Duplicate event ${key}`); keys.add(key);
    assert.equal(event.signature, toEventSignature(event.abi));
    assert.ok(event.description.trim(), `Missing description: ${key}`);
    assert.deepEqual(event.parameters.map(p => [p.name, p.type, p.indexed]), event.abi.inputs.map(p => [p.name, p.type, p.indexed ?? false]));
    for (const p of event.parameters) {
      ident(p.name);
      assert.ok(p.semantic.unit && p.semantic.description.trim(), `Missing semantic: ${key}.${p.name}`);
      if (p.semantic.unit === 'raw-amount') assert.ok(p.semantic.asset && p.semantic.decimals, `Missing asset/decimals: ${key}.${p.name}`);
    }
  }
  for (const contract of manifest.contracts) {
    const abi = ponsIndexingAbis[contract.name];
    assert.ok(abi, `Unknown ABI ${contract.name}`);
    assert.deepEqual(manifest.catalog.filter(e => e.contract === contract.name).map(e => e.signature), abi.filter(e => e.type === 'event').map(toEventSignature), `Incomplete ABI coverage: ${contract.name}`);
  }
  for (const contract of [...manifest.contracts, ...manifest.dependencies]) {
    assert.deepEqual(contract.events, manifest.catalog.filter(e => e.contract === contract.name).map(e => e.name), `Event list drift: ${contract.name}`);
    assert.ok(manifest.sources.some(s => s.contract === contract.name), `Missing source: ${contract.name}`);
  }
  for (const source of manifest.sources) {
    assert.ok([...manifest.contracts, ...manifest.dependencies].some(c => c.name === source.contract));
    if (source.kind === 'dynamic') {
      const rule = source.registeredBy;
      assert.equal(parameter(eventFor(rule.contract, rule.event), rule.addressParameter).type, 'address');
      assert.equal(source.startFrom, 'discovery-block');
    }
  }
  for (const entity of manifest.materializations) {
    ident(entity.name);
    for (const field of Object.keys(entity.fields)) ident(field);
    for (const update of entity.updates) {
      const event = eventFor(update.contract, update.event);
      const valueType = value => {
        const type = 'parameter' in value ? parameter(event, value.parameter).type : value.event === 'block.number' ? 'uint256' : 'address';
        if (value.lowercase) assert.match(type, /^(address|bytes\d*|string)$/);
        return /^(u?int)/.test(type) ? 'BigInt' : 'String';
      };
      assert.equal(valueType(update.key), 'String', 'Entity key must be an address or identifier');
      if (update.when) assert.equal(parameter(event, update.when.parameter).type, 'address');
      for (const [field, value] of Object.entries(update.set)) {
        assert.ok(entity.fields[field], `Unknown field ${entity.name}.${field}`);
        assert.equal(entity.fields[field].type, valueType(value), `Type mismatch: ${entity.name}.${field}`);
      }
      for (const [field, definition] of Object.entries(entity.fields)) {
        if (definition.required) assert.ok(update.set[field], `Required field absent on partial create: ${field}`);
      }
      for (const field of update.assertUnchanged ?? []) assert.ok(update.set[field], `Assertion without assignment: ${field}`);
    }
  }
  for (const dependency of manifest.dependencies) for (const filter of dependency.filters) {
    const input = parameter(eventFor(dependency.name, filter.event), filter.parameter);
    const registration = filter.includeWhenRegisteredBy;
    const registered = parameter(eventFor(registration.contract, registration.event), registration.parameter);
    assert.equal(input.type, registered.type);
    membershipEntity(manifest, registration);
  }
}

function membershipEntity(manifest, registration) {
  const matches = manifest.materializations.filter(entity => entity.updates.some(update =>
    update.contract === registration.contract && update.event === registration.event && update.key.parameter === registration.parameter && update.key.lowercase));
  assert.equal(matches.length, 1, 'Membership registration must name one materialized key');
  return matches[0].name;
}
const expression = value => {
  const base = 'parameter' in value ? `event.params.${value.parameter}` : value.event === 'block.number' ? 'BigInt(event.block.number)' : 'event.srcAddress';
  return base + (value.lowercase ? '.toLowerCase()' : '');
};
function renderUpdate(entity, rule) {
  const lines = ['    {'];
  if (rule.when) lines.push(`      if (event.params.${rule.when.parameter}.toLowerCase() === ${q(rule.when.equals.toLowerCase())}) {`);
  lines.push(`      const id = chainKey(event.chainId, ${expression(rule.key)});`, `      const existing = await context.${entity.name}.get(id);`);
  for (const field of rule.assertUnchanged ?? []) lines.push(
    `      if (existing?.${field} != null && existing.${field} !== ${expression(rule.set[field])}) {`,
    `        throw new Error(${q(`Conflicting ${entity.name}.${field} evidence for `)} + id);`, '      }');
  lines.push(`      context.${entity.name}.set({`, '        id,');
  for (const field of Object.keys(entity.fields)) lines.push(`        ${field}: ${rule.set[field] ? expression(rule.set[field]) : `existing?.${field}`},`);
  lines.push('      });');
  if (rule.when) lines.push('      }');
  lines.push('    }');
  return lines.join('\n');
}

export function renderIndexing(manifest = getPonsIndexingManifest()) {
  validateCatalog(manifest);
  const outputs = new Map();
  outputs.set('indexing/mainnet.json', json(manifest));
  for (const [contract, abi] of Object.entries(ponsIndexingAbis)) {
    const events = json(abi.filter(e => e.type === 'event').map(e => ({ ...e, anonymous: e.anonymous ?? false, inputs: e.inputs.map(p => ({ ...p, indexed: p.indexed ?? false })) })));
    outputs.set(`artifacts/${contract}.json`, events);
    outputs.set(`examples/envio/abis/${contract}.json`, events);
  }
  const config = {
    name: 'pons-v2-mainnet-example', description: 'Generated Pons event log, source discovery, and materialized evidence.',
    rollback_on_reorg: true, raw_events: false, address_format: 'lowercase', handlers: './src/EventHandlers.ts',
    full_batch_size: 5000, storage: { postgres: { default: true } },
    field_selection: { transaction_fields: ['hash', 'transactionIndex'] },
    contracts: [...manifest.contracts, ...manifest.dependencies].map(c => ({ name: c.name, abi_file_path: `./abis/${c.name}.json`, events: c.events.map(event => ({ event })) })),
    chains: [{ id: manifest.chainId, start_block: Number(manifest.startBlock), block_lag: 2, max_reorg_depth: 200,
      hypersync_config: { url: `https://${manifest.chainId}.hypersync.xyz` },
      rpc: [ { url: '${ENVIO_ROBINHOOD_MAINNET_RPC_URL}', for: 'fallback', initial_block_interval: 2000, interval_ceiling: 10000, backoff_millis: 2000, query_timeout_millis: 20000 }, { url: '${ENVIO_ROBINHOOD_MAINNET_RPC_URL}', for: 'realtime', query_timeout_millis: 10000, polling_interval: 25000 } ],
      contracts: manifest.sources.filter(s => s.kind === 'fixed').map(s => ({ name: s.contract, start_block: Number(s.startBlock), address: [s.address.toLowerCase()] })),
    }],
  };
  outputs.set('examples/envio/config.yaml', '# Generated by scripts/generate-indexing.mjs. Do not edit.\n' + stringify(config));
  const schema = manifest.materializations.map(e => `"""${e.description}"""\ntype ${e.name} {\n  id: ID!\n${Object.entries(e.fields).map(([name, field]) => `  ${name}: ${field.type}${field.required ? '!' : ''}${field.index ? ' @index' : ''}`).join('\n')}\n}`).join('\n\n');
  outputs.set('examples/envio/schema.graphql', '# Generated by scripts/generate-indexing.mjs. Do not edit.\n' + schema + `

"""Append-only canonical event history; Envio rolls back orphaned rows and entities together."""
type PonsProtocolEvent {
  id: ID!
  chainId: BigInt! @index
  kind: String! @index
  signature: String!
  contract: String! @index
  sourceAddress: String! @index
  transactionHash: String! @index
  transactionIndex: BigInt!
  blockNumber: BigInt! @index
  blockHash: String!
  blockTimestamp: BigInt!
  logIndex: BigInt!
  payload: String!
}
`);
  let handlers = banner + `import { indexer } from 'envio';
import { chainKey, normalizedEvent } from './eventLog.js';
`;
  const registrations = new Map();
  for (const source of manifest.sources.filter(s => s.kind === 'dynamic')) {
    const r = source.registeredBy;
    const key = JSON.stringify({ contract: r.contract, event: r.event });
    registrations.set(key, [...(registrations.get(key) ?? []), `    context.chain.${source.contract}.add(event.params.${r.addressParameter});`]);
  }
  for (const [key, statements] of registrations) handlers += `\nindexer.contractRegister(${key}, async ({ event, context }) => {\n${statements.join('\n')}\n});\n`;
  for (const event of manifest.catalog) {
    handlers += `\nindexer.onEvent(${JSON.stringify({ contract: event.contract, event: event.name })}, async ({ event, context }) => {\n`;
    for (const dependency of manifest.dependencies.filter(d => d.name === event.contract)) for (const filter of dependency.filters.filter(f => f.event === event.name)) {
      handlers += `    if (!await context.${membershipEntity(manifest, filter.includeWhenRegisteredBy)}.get(chainKey(event.chainId, event.params.${filter.parameter}))) return;\n`;
    }
    handlers += `    context.PonsProtocolEvent.set(normalizedEvent(event, ${q(event.contract)}, ${q(event.name)}, ${q(event.signature)}));\n`;
    for (const entity of manifest.materializations) for (const rule of entity.updates.filter(u => u.contract === event.contract && u.event === event.name)) handlers += renderUpdate(entity, rule) + '\n';
    handlers += '});\n';
  }
  outputs.set('examples/envio/src/EventHandlers.ts', handlers);
  outputs.set('examples/envio/src/eventLog.ts', banner + readFileSync(resolve(root, 'scripts/indexing-event-log.ts.template'), 'utf8'));
  return outputs;
}

// These directories contain only generator-owned artifacts. Other starter files
// (README, npm lockfile) are maintained inputs, never removed by generation.
export function generatedPaths(directory) {
  const result = ['examples/envio/config.yaml', 'examples/envio/schema.graphql'];
  for (const folder of ['artifacts', 'indexing', 'examples/envio/src', 'examples/envio/abis']) {
    if (existsSync(resolve(directory, folder))) for (const name of readdirSync(resolve(directory, folder))) result.push(`${folder}/${name}`);
  }
  return result;
}
export function generate({ directory = root, check = false, manifest = getPonsIndexingManifest() } = {}) {
  const outputs = renderIndexing(manifest);
  const stale = generatedPaths(directory).filter(path => !outputs.has(path));
  const changed = [...outputs].filter(([path, content]) => !existsSync(resolve(directory, path)) || readFileSync(resolve(directory, path), 'utf8') !== content).map(([path]) => path);
  if (check) {
    assert.deepEqual([...changed, ...stale], [], 'Indexing output drift; run npm run generate:indexing');
  } else {
    for (const path of stale) rmSync(resolve(directory, path));
    for (const [path, content] of outputs) { mkdirSync(dirname(resolve(directory, path)), { recursive: true }); writeFileSync(resolve(directory, path), content); }
  }
  return outputs;
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  assert.ok(process.argv.slice(2).every(arg => arg === '--check'), 'Usage: node scripts/generate-indexing.mjs [--check]');
  generate({ check: process.argv.includes('--check') });
  console.log(process.argv.includes('--check') ? 'Indexing output matches catalog.' : 'Generated indexing artifacts and Envio starter.');
}
